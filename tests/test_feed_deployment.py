def _git_blob(commit: str, path: str) -> bytes:
    completed = subprocess.run(
        ["git", "show", f"{commit}:{path}"],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
    )
    return completed.stdout


def _git_tree_names(commit: str, path: str) -> list[str]:
    completed = subprocess.run(
        ["git", "ls-tree", "--name-only", f"{commit}:{path}"],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.splitlines()


def build_production_runtime_state(
    runtime_root: Path, *, commit: str = PRODUCTION_STATE_COMMIT
) -> None:
    """Materialize the trusted ``f7095a5`` production runtime state into ``runtime_root``.

    Provenance: every file is extracted verbatim from the git blobs of commit
    ``f7095a5`` ("feeds: failure") — the checkpoint, terminal-failure lease,
    RateRegistry, and all four rate scope files (including the tolerated
    obsolete ``yahoo_market`` scope ``scope-3b806f91752a2756.json``).

    Rewrite rule: the builder replaces the registry's ``root_identity`` (the
    GitHub Hosted Runner path recorded in production) with the fixture
    runtime root's ``resolve()`` so the fail-closed registry check accepts the
    temporary fixture root. This rewrite happens inside the test builder only;
    production restores never rewrite ``root_identity``.
    """
    runtime_root.mkdir(parents=True, exist_ok=True)
    for name in _git_tree_names(commit, ".feed-state"):
        (runtime_root / name).write_bytes(_git_blob(commit, f".feed-state/{name}"))
    registry_path = runtime_root / "rate-registry.json"
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    assert registry["root_identity"] == PRODUCTION_REGISTRY_ROOT
    registry["root_identity"] = str(runtime_root.resolve())
    registry_path.write_text(
        json.dumps(registry, sort_keys=True, separators=(",", ":")), encoding="utf-8"
    )


def build_production_state_fixture(
    runtime_root: Path, product_root: Path, *, commit: str = PRODUCTION_STATE_COMMIT
) -> None:
    """Materialize the trusted ``f7095a5`` runtime state and v3 Feed product.

    Same provenance and rewrite rule as ``build_production_runtime_state``;
    additionally extracts the v3 eight-domain Feed bundle inventoried by
    ``feeds/feed-manifest.json`` into ``product_root`` verbatim. The v3
    product is used only to pin the fail-closed rejection of this bundle as a
    migration input under the current accepted contracts (ECO-124 changed
    cftc's ``empty_valid_for_window``); production restores never place it in
    ``feeds/``.
    """
    build_production_runtime_state(runtime_root, commit=commit)
    product_root.mkdir(parents=True, exist_ok=True)
    for name in _git_tree_names(commit, "feeds"):
        (product_root / name).write_bytes(_git_blob(commit, f"feeds/{name}"))


