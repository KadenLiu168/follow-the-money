def test_success_and_failure_finalization_keep_exact_paths(tmp_path: Path):
    prepare_deployment(tmp_path, _cfg(_policy()), deployment_run_id="42-1", now=_clock(NOW))
    armed_at = NOW + timedelta(days=1)
    prepare_deployment(tmp_path, _cfg(_policy()), deployment_run_id="43-1", now=_clock(armed_at))
    feed = _healthy_feed()
    run_id = feed["run_id"]
    _product_root(tmp_path).mkdir(parents=True)
    bundle = build_bundle(feed)
    publish_bundle(
        output_root=_product_root(tmp_path),
        bundle=bundle,
        cutoff=datetime.fromisoformat(feed["evidence_cutoff_at"]),
        run_id=run_id,
    )
    status = tmp_path / "feed-status.json"
    status.write_text(
        json.dumps(
            {
                "status": "healthy",
                "run_id": run_id,
                "evidence_cutoff_at": feed["evidence_cutoff_at"],
                "manifest_relative_path": "feed-manifest.json",
            }
        ),
        encoding="utf-8",
    )
    write_checkpoint(
        tmp_path / "feed-checkpoint.json",
        FeedCheckpoint(
            previous_success=PreviousSuccess(
                evidence_cutoff_at=feed["evidence_cutoff_at"],
                run_id=run_id,
            )
        ),
    )
    paths = finalize_deployment(
        tmp_path,
        deployment_run_id="43-1",
        feed_succeeded=True,
        status_path=status,
        now=_clock(armed_at + timedelta(seconds=1)),
    )
    assert {path.name for path in paths} >= {"feed-run-lease.json", "feed-manifest.json"}
    assert read_lease(tmp_path / "feed-run-lease.json").state == "success"

    prepare_deployment(
        tmp_path,
        _cfg(_policy()),
        deployment_run_id="44-1",
        now=_clock(armed_at + timedelta(days=2)),
    )
    failure_paths = finalize_deployment(
        tmp_path,
        deployment_run_id="44-1",
        feed_succeeded=False,
        status_path=status,
        now=_clock(armed_at + timedelta(days=2, seconds=1)),
    )
    assert all(path.name not in {"latest.json", f"{run_id}.json"} for path in failure_paths)
    assert read_lease(tmp_path / "feed-run-lease.json").state == "failure"


